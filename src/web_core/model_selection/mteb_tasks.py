# --- Lookup ------------------------------------------------------------------

_FALLBACK_SUFFIXES: tuple[tuple[str, str], ...] = (
    ("Classification", "classification"),
    ("Reranking", "reranking"),
    ("Retrieval", "retrieval"),
    ("STS", "sts"),
)

# Hard-negatives eval variants (``X...HardNegatives``) score the same family
# as their base task, e.g. ``MIRACLRetrievalHardNegatives`` -> retrieval.
_HARD_NEGATIVES_SUFFIX = "HardNegatives"

_FALLBACK_PREFIXES: tuple[tuple[str, str], ...] = (("STS", "sts"),)

# ``*PairClassification`` is the pair-classification family (outside the four
# supported families) but would otherwise be swallowed by the
# ``Classification`` suffix rule below.
_EXCLUDED_SUFFIXES: tuple[str, ...] = ("PairClassification",)

# Names carried by historical ``mteb/results`` rows that newer mteb versions
# renamed (checked after the exact sets, before suffix fallback).
_LEGACY_ALIASES: dict[str, str] = {
    "MTOPIntent": "classification",  # renamed to MTOPIntentClassification
    "SciDocs": "retrieval",  # superseded by SciDocsRR / *Retrieval variants
    "CQADupstack": "retrieval",  # v1 aggregate of the CQADupstack*Retrieval tasks
    "Touche2021": "retrieval",  # exact sets only carry Touche2020 / Touche20xxRetrieval
    "Touche2022": "retrieval",
    "Touche2023": "retrieval",
    "SemRel": "sts",  # renamed to SemRel24STS
}

_EXACT: dict[str, str] = {}
for _names, _family in (
    (CLASSIFICATION_TASKS, "classification"),
    (RETRIEVAL_TASKS, "retrieval"),
    (STS_TASKS, "sts"),
    (RERANKING_TASKS, "reranking"),
):
    for _name in _names:
        _EXACT.setdefault(_name, _family)

# Case-folded view used only to resolve the base task of a ``*HardNegatives``
# variant (e.g. ``FeverHardNegatives`` -> ``FEVER``); unknown names must stay
# ``None``, so the main lookup remains case-sensitive.
_EXACT_CI: dict[str, str] = {_name.casefold(): _family for _name, _family in _EXACT.items()}


def task_family(task_name: str) -> str | None:
    """Map a raw ``mteb/results`` ``task_name`` to a family name, or ``None``.

    Families: ``classification``, ``retrieval``, ``sts``, ``reranking``.
    """
    family = _EXACT.get(task_name)
    if family is None:
        family = _LEGACY_ALIASES.get(task_name)
    if family is not None:
        return family
    for suffix in _EXCLUDED_SUFFIXES:
        if task_name.endswith(suffix):
            return None
    for suffix, family in _FALLBACK_SUFFIXES:
        if task_name.endswith(suffix):
            return family
    if task_name.endswith(_HARD_NEGATIVES_SUFFIX):
        base = task_name[: -len(_HARD_NEGATIVES_SUFFIX)]
        if base:
            return task_family(base) or _EXACT_CI.get(base.casefold())
    for prefix, family in _FALLBACK_PREFIXES:
        if task_name.startswith(prefix):
            return family
    return None
