"""MTEB task-name -> task-family taxonomy for the ``mteb_*`` fetchers.

Source of truth: ``embeddings-benchmark/mteb`` (mteb==2.21.8) task metadata
names, extracted per task-type folder from the published wheel. The HF
``mteb/results`` dataset tags every row with a raw ``task_name`` (e.g.
``"Banking77Classification"``, ``"ArguAna"``, ``"STS22"``) but carries no
task-type column, so family classification is name-based:

1. exact match against the sets below (canonical for known tasks, covering
   the many names that do not follow a suffix convention, e.g. ``ArguAna``,
   ``BIOSSES``, ``AskUbuntuDupQuestions``);
2. suffix/prefix fallback for task names added to newer MTEB versions after
   this table was generated (``*Classification``, ``*Reranking``,
   ``*Retrieval``, ``*RetrievalHardNegatives``, ``STS*``/``*STS``);
3. ``None`` -> the row is ignored (clustering, pair classification,
   summarization, bitext mining, ... are outside the four supported
   families).

Regenerate the exact-match sets with mteb installed::

    python - <<'PY'
    import mteb, json
    from mteb.get_tasks import MTEBTaskList  # noqa
    PY
    # or: walk mteb/tasks/<type>/*.py and collect TaskMetadata(name=...)

Unknown-name handling is fail-open by design: a newer dataset with task
names this table does not know only loses those rows, never crashes. The
suffix fallback also covers the ``XRetrievalHardNegatives`` hard-negatives
variants present in the dataset but absent from mteb 2.21.8.
"""

